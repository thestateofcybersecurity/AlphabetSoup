-- ---------------------------------------------------------------------------
-- 5. Flight recorder: append-only, hash-chained per tenant
-- ---------------------------------------------------------------------------
-- The app may INSERT, and only INSERT. A consultant acting in a customer tenant writes an event
-- to the customer's chain AND to their firm's chain, so the insert policy allows both the acting
-- and the home tenant. Reads stay acting-tenant only.
create table if not exists outpost.audit_events (
  tenant_id             uuid not null references platform.tenants (id),
  seq                   bigint not null,
  at                    timestamptz not null default now(),
  actor_user_id         uuid,
  actor_home_tenant_id  uuid,
  engagement_id         uuid,
  action                text not null,                 -- 'session.switch', 'finding.read', 'sortie.approve', ...
  resource_kind         text,
  resource_id           uuid,
  target_tenant_id      uuid,                          -- set on cross-tenant attempts (always denied)
  request_id            text,
  ip                    inet,
  detail                jsonb not null default '{}',
  prev_hash             bytea,
  hash                  bytea not null,
  primary key (tenant_id, seq)
);

-- Serializes per tenant, links to the previous row, computes the hash. SECURITY DEFINER so it can
-- read the previous row of the home tenant's chain while the session is scoped to the acting
-- tenant; audit_events is therefore ENABLED but not FORCED (owner-bypass is what makes the
-- lookup work). check_rls.sql carries this one table as a named exception.
create or replace function outpost.audit_chain() returns trigger
  language plpgsql security definer set search_path = outpost, pg_temp as $$
declare
  last_seq  bigint;
  last_hash bytea;
begin
  perform pg_advisory_xact_lock(hashtext(new.tenant_id::text));
  select seq, hash into last_seq, last_hash
    from outpost.audit_events where tenant_id = new.tenant_id order by seq desc limit 1;
  new.seq       := coalesce(last_seq, 0) + 1;
  new.at        := coalesce(new.at, now());
  new.prev_hash := last_hash;
  new.hash      := sha256(coalesce(last_hash, '\x'::bytea) || convert_to(
                     concat_ws('|', new.tenant_id, new.seq, new.at, new.actor_user_id, new.actor_home_tenant_id,
                               new.engagement_id, new.action, new.resource_kind, new.resource_id,
                               new.target_tenant_id, new.request_id, new.detail::text), 'UTF8'));
  return new;
end $$;

drop trigger if exists audit_chain on outpost.audit_events;
create trigger audit_chain before insert on outpost.audit_events
  for each row execute function outpost.audit_chain();

-- Nightly: verify a tenant's chain end to end. Returns the first broken seq, or null.
create or replace function outpost.audit_verify(p_tenant uuid) returns bigint
  language plpgsql security definer set search_path = outpost, pg_temp as $$
declare
  r         record;
  expected  bytea;
  prev      bytea := null;
begin
  for r in select * from outpost.audit_events where tenant_id = p_tenant order by seq loop
    expected := sha256(coalesce(prev, '\x'::bytea) || convert_to(
                  concat_ws('|', r.tenant_id, r.seq, r.at, r.actor_user_id, r.actor_home_tenant_id,
                            r.engagement_id, r.action, r.resource_kind, r.resource_id,
                            r.target_tenant_id, r.request_id, r.detail::text), 'UTF8'));
    if r.hash <> expected or r.prev_hash is distinct from prev then
      return r.seq;
    end if;
    prev := r.hash;
  end loop;
  return null;
end $$;

alter table outpost.audit_events enable row level security;
drop policy if exists audit_read on outpost.audit_events;
create policy audit_read on outpost.audit_events for select
  using (tenant_id = outpost.tenant());
drop policy if exists audit_insert on outpost.audit_events;
create policy audit_insert on outpost.audit_events for insert
  with check (tenant_id = outpost.tenant() or tenant_id = outpost.home_tenant());

