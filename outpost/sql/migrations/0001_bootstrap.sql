-- Outpost Postgres schema, v0.1 (2026-09-18). Companion to README.md and TENANT-ISOLATION.md.
--
-- Layout
--   platform.*  tenants, users, sessions, engagements. No tenant data, no RLS. Owned by
--               outpost_migrate; the request-path role gets narrow grants.
--   catalog.*   shared, read-only reference data: connector types, missions, playbooks,
--               agents, MCP allowlist. No tenant_id by design.
--   outpost.*   every tenant-scoped table. tenant_id NOT NULL on all of them, defaulting to
--               the request's acting tenant, with RLS ENABLED and FORCED and a
--               tenant_isolation policy. check_rls.sql fails CI if any table here breaks that.
--
-- Roles
--   outpost_migrate      owns everything, runs this file and migrations. Never used by the app.
--   outpost_app          request path. NOBYPASSRLS. DML on outpost.*, INSERT-only on audit.
--   outpost_provisioner  tenant creation and offboarding job. Writes platform.tenants.
--
-- Conventions
--   Ids are UUIDv7 generated by the application (time-ordered, no sequence to leak counts);
--   gen_random_uuid() is the fallback default so raw SQL in tests still works.
--   Enumerations are text + CHECK so a new value is a migration, not a type rebuild.
--   Child tables reference parents by (tenant_id, id) so a row can never point across tenants.
--
-- Run: psql -v ON_ERROR_STOP=1 -f schema.sql   (as a superuser the first time, for the roles)

\set ON_ERROR_STOP on

-- ---------------------------------------------------------------------------
-- 0. Roles (superuser section). Idempotent.
-- ---------------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'outpost_migrate') then
    create role outpost_migrate login;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'outpost_app') then
    create role outpost_app login nobypassrls;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'outpost_provisioner') then
    create role outpost_provisioner login nobypassrls;
  end if;
end $$;

grant create on database :DBNAME to outpost_migrate;

set role outpost_migrate;

create schema if not exists platform authorization outpost_migrate;
create schema if not exists catalog  authorization outpost_migrate;
create schema if not exists outpost  authorization outpost_migrate;

-- ---------------------------------------------------------------------------
-- 1. Tenant context helpers
-- ---------------------------------------------------------------------------
-- The middleware runs, inside the request transaction:
--   SET LOCAL app.tenant_id      = '<acting tenant uuid>';
--   SET LOCAL app.home_tenant_id = '<actor home tenant uuid>';
--   SET LOCAL app.user_id        = '<actor user uuid>';
-- Unset means NULL, and NULL never equals a tenant_id, so an unscoped session sees nothing
-- and can insert nothing. Fail closed.

create or replace function outpost.tenant() returns uuid
  language sql stable parallel safe
  as $$ select nullif(current_setting('app.tenant_id', true), '')::uuid $$;

create or replace function outpost.home_tenant() returns uuid
  language sql stable parallel safe
  as $$ select nullif(current_setting('app.home_tenant_id', true), '')::uuid $$;

create or replace function outpost.actor() returns uuid
  language sql stable parallel safe
  as $$ select nullif(current_setting('app.user_id', true), '')::uuid $$;

-- Standard protection for a tenant table: enable + force RLS, one isolation policy.
create or replace procedure outpost.protect(tbl regclass)
  language plpgsql as $$
begin
  execute format('alter table %s enable row level security', tbl);
  execute format('alter table %s force row level security', tbl);
  execute format('drop policy if exists tenant_isolation on %s', tbl);
  execute format(
    'create policy tenant_isolation on %s using (tenant_id = outpost.tenant()) with check (tenant_id = outpost.tenant())',
    tbl);
end $$;

create or replace function outpost.touch() returns trigger
  language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

-- ---------------------------------------------------------------------------
-- 2. platform.*  (no tenant data)
-- ---------------------------------------------------------------------------
create table if not exists platform.tenants (
  id             uuid primary key default gen_random_uuid(),
  kind           text not null check (kind in ('customer', 'firm')),
  name           text not null,
  slug           text not null unique,
  status         text not null default 'active' check (status in ('provisioning', 'active', 'suspended', 'offboarding', 'offboarded')),
  kms_key_arn    text,
  es_alias       text unique,
  redis_prefix   text unique,
  created_at     timestamptz not null default now(),
  offboarded_at  timestamptz,
  unique (id, kind)                                   -- lets engagements pin the kind by FK
);

create table if not exists platform.users (
  id              uuid primary key default gen_random_uuid(),
  home_tenant_id  uuid not null references platform.tenants (id),
  idp_subject     text not null unique,
  email           text not null,
  display_name    text not null,
  mfa_kind        text not null default 'none' check (mfa_kind in ('none', 'totp', 'webauthn')),
  status          text not null default 'active' check (status in ('invited', 'active', 'disabled')),
  created_at      timestamptz not null default now(),
  unique (home_tenant_id, email)
);

-- One row per issued access token family. Revocation is checked on every request.
create table if not exists platform.sessions (
  sid               uuid primary key,
  user_id           uuid not null references platform.users (id),
  home_tenant_id    uuid not null references platform.tenants (id),
  acting_tenant_id  uuid not null references platform.tenants (id),
  engagement_id     uuid,                              -- set when acting_tenant != home_tenant
  role              text not null,
  issued_at         timestamptz not null default now(),
  expires_at        timestamptz not null,
  revoked_at        timestamptz,
  revoked_reason    text,
  ip                inet,
  user_agent        text
);
create index if not exists sessions_user_idx on platform.sessions (user_id, issued_at desc);

create table if not exists platform.engagements (
  id                  uuid primary key default gen_random_uuid(),
  firm_tenant_id      uuid not null,
  firm_kind           text not null default 'firm' check (firm_kind = 'firm'),
  customer_tenant_id  uuid not null,
  customer_kind       text not null default 'customer' check (customer_kind = 'customer'),
  starts_at           timestamptz not null default now(),
  ends_at             timestamptz not null,
  status              text not null default 'active' check (status in ('draft', 'active', 'ended', 'terminated')),
  created_by          uuid not null references platform.users (id),
  created_at          timestamptz not null default now(),
  check (ends_at > starts_at),
  foreign key (firm_tenant_id, firm_kind)         references platform.tenants (id, kind),
  foreign key (customer_tenant_id, customer_kind) references platform.tenants (id, kind)
);
create index if not exists engagements_customer_idx on platform.engagements (customer_tenant_id, status);
create index if not exists engagements_firm_idx     on platform.engagements (firm_tenant_id, status);

-- A consultant reaches a customer tenant only through an unrevoked row here, inside the
-- engagement window. The customer can revoke; the firm cannot override that.
create table if not exists platform.engagement_assignments (
  id             uuid primary key default gen_random_uuid(),
  engagement_id  uuid not null references platform.engagements (id),
  user_id        uuid not null references platform.users (id),
  role           text not null check (role in ('lead', 'analyst')),
  granted_by     uuid not null references platform.users (id),
  granted_at     timestamptz not null default now(),
  revoked_by     uuid references platform.users (id),
  revoked_at     timestamptz,
  revoked_side   text check (revoked_side in ('firm', 'customer')),
  unique (engagement_id, user_id)
);

alter table platform.sessions
  add constraint sessions_engagement_fk foreign key (engagement_id) references platform.engagements (id);

-- Counts only. Written by each tenant's own jobs; read by the Command Deck fleet view.
-- This is the only thing a consultant sees across clients without switching context.
create table if not exists platform.engagement_summaries (
  engagement_id         uuid primary key references platform.engagements (id),
  missions_due          integer not null default 0,
  approvals_waiting     integer not null default 0,
  sorties_failed_7d     integer not null default 0,
  findings_open         integer not null default 0,
  findings_critical     integer not null default 0,
  connectors_unhealthy  integer not null default 0,
  posture_band          text,
  as_of                 timestamptz not null default now()
);

create table if not exists platform.break_glass_grants (
  id               uuid primary key default gen_random_uuid(),
  tenant_id        uuid not null references platform.tenants (id),
  admin_user_id    uuid not null references platform.users (id),
  approver_user_id uuid not null references platform.users (id),
  reason           text not null,
  starts_at        timestamptz not null default now(),
  ends_at          timestamptz not null,
  revoked_at       timestamptz,
  check (admin_user_id <> approver_user_id),
  check (ends_at <= starts_at + interval '4 hours')
);

