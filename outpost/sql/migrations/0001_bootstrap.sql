create table if not exists catalog.playbooks (
  id                 text primary key,
  domain             text not null,
  title              text not null,
  summary            text not null,
  agent_id           text not null references catalog.agents (id),
  mcp_server_ids     text[] not null,
  blast_radius       text not null check (blast_radius in ('low', 'medium', 'high')),
  reversible         boolean not null,
  mode_ceiling       text not null check (mode_ceiling in ('autopilot', 'clearance', 'beacon')),
  required_capabilities text[] not null,              -- write scopes it needs
  resolves_checks    text[] not null,                 -- catalog.missions checks it can close
  call_schema        jsonb not null,                  -- allowed tool calls + parameter constraints
  verification       jsonb not null,                  -- the check to re-run after execution
  rollback           jsonb,                           -- null when not reversible
  default_cadence    text not null,                   -- cron or 'on-finding'
  version            integer not null default 1,
  check ((reversible and rollback is not null) or (not reversible and mode_ceiling <> 'autopilot'))
);

