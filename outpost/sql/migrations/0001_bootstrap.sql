-- One execution of a playbook ("sortie"). Mirrors the Temporal workflow; Postgres is the record.
create table if not exists outpost.sorties (
  tenant_id             uuid not null default outpost.tenant() references platform.tenants (id),
  id                    uuid primary key default gen_random_uuid(),
  playbook_id           text not null references catalog.playbooks (id),
  enablement_id         uuid,
  trigger               text not null check (trigger in ('scheduled', 'manual', 'on_finding')),
  mode                  text not null check (mode in ('autopilot', 'clearance', 'beacon')),
  status                text not null default 'planning'
                        check (status in ('planning', 'previewed', 'awaiting_clearance', 'approved', 'executing',
                                          'verifying', 'succeeded', 'verification_failed', 'rolled_back',
                                          'rollback_failed', 'rejected', 'expired', 'cancelled', 'failed')),
  temporal_workflow_id  text unique,
  finding_ids           uuid[] not null default '{}',
  preview               jsonb,                         -- the exact calls it will make
  preview_hash          bytea,                         -- sha256(canonical(preview)); approvals bind to this
  plan_summary          text,                          -- agent's explanation for the approver
  requested_by          uuid,
  run_credentials_expire_at timestamptz,
  started_at            timestamptz,
  executed_at           timestamptz,
  finished_at           timestamptz,
  result                jsonb,
  verification          jsonb,
  killed_at             timestamptz,
  killed_by             uuid,
  created_at            timestamptz not null default now(),
  unique (tenant_id, id),
  foreign key (tenant_id, enablement_id) references outpost.playbook_enablements (tenant_id, id)
);
