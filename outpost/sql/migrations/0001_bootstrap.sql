-- 6. Apply RLS to every tenant table, and updated_at triggers
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  for t in
    select format('%I.%I', schemaname, tablename) from pg_tables
     where schemaname = 'outpost' and tablename <> 'audit_events'
  loop
    call outpost.protect(t::regclass);
  end loop;
end $$;

do $$
declare t text;
begin
  for t in
    select format('%I.%I', c.table_schema, c.table_name) from information_schema.columns c
     where c.table_schema = 'outpost' and c.column_name = 'updated_at'
  loop
    execute format('drop trigger if exists touch on %s', t);
    execute format('create trigger touch before update on %s for each row execute function outpost.touch()', t);
  end loop;
end $$;

